from sqlalchemy import create_engine, text
from config import DATABASE_URL

def engine():
    return create_engine(DATABASE_URL, future=True, pool_pre_ping=True)

def initialize_db():
    eng = engine()
    if DATABASE_URL.startswith("sqlite"):
        sql = """CREATE TABLE IF NOT EXISTS churn_predictions (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            customer_label TEXT,
            prediction TEXT NOT NULL,
            probability REAL NOT NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )"""
    else:
        sql = """CREATE TABLE IF NOT EXISTS churn_predictions (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            customer_label VARCHAR(100),
            prediction VARCHAR(20) NOT NULL,
            probability DOUBLE PRECISION NOT NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )"""
    with eng.begin() as conn:
        conn.execute(text(sql))
    return eng

def save_prediction(label, prediction, probability):
    eng = initialize_db()
    with eng.begin() as conn:
        conn.execute(text("""INSERT INTO churn_predictions
            (customer_label, prediction, probability)
            VALUES (:label, :prediction, :probability)"""),
            {"label": label or "Anonymous", "prediction": prediction,
             "probability": float(probability)})

def history():
    eng = initialize_db()
    with eng.connect() as conn:
        result = conn.execute(text("""SELECT id, customer_label, prediction,
            probability, created_at FROM churn_predictions ORDER BY id DESC LIMIT 200"""))
        return [dict(row._mapping) for row in result]
